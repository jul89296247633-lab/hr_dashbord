-- 20260524150000_bonus_rates_aliases_cleanup.sql
--
-- 8 алиасов для типовых названий из листа Data, которые не дотягивали до
-- pg_trgm threshold 0.4 относительно полного каталога:
--   - «Продавец-консультант» / «Менеджер-консультант» — 10+5 закрытий мая
--   - «Хостес/администратор» (vs «Хостес»)
--   - «Менеджер по подбору персонала» / «Рекрутер» (vs «HR-менеджер»)
--   - «Оператор видеоконтроля» (vs «Оператор видеонаблюдения»)
--   - «Руководитель отдела продаж» (vs «Руководитель розницы»)
--   - «Специалист по воинскому учету» (одна вакансия с латинскими омоглифами;
--     добавляем кириллический вариант, латиница так и останется без тарифа).
--
-- Плюс DELETE 3-х orphan записей от первого seed (20260523210000), где имена
-- были упрощёнными — теперь в каталоге есть точные варианты.
-- ════════════════════════════════════════════════════════════════════════

INSERT INTO public.bonus_rates (position_name, amount_kopecks, group_name) VALUES
  ('Продавец-консультант',                600000, 'Розница'),
  ('Менеджер-консультант',                700000, 'Розница'),
  ('Хостес/администратор',                300000, 'Розница'),
  ('Менеджер по подбору персонала',      1000000, 'Офис'),
  ('Рекрутер',                           1000000, 'Офис'),
  ('Оператор видеоконтроля',              400000, 'Офис'),
  ('Руководитель отдела продаж',         1500000, 'Офис'),
  ('Специалист по воинскому учету',       500000, 'Офис')
ON CONFLICT (position_name) DO UPDATE SET
  amount_kopecks = EXCLUDED.amount_kopecks,
  group_name     = EXCLUDED.group_name;

DELETE FROM public.bonus_rates
WHERE position_name IN (
  'Помощник управляющего',
  'Специалист охраны',
  'Оператор колл-центра'
);
