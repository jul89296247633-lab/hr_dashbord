-- Добавляем поле приоритета вакансии. Используется на /vacancies для
-- цветовой маркировки строк (красный/жёлтый/серый) и в будущем — для
-- сортировки/фильтрации. Значения — русскоязычный набор, как HR пишет
-- в листе Data (колонка «Приоритет», если есть).
--
-- Nullable: исторические записи и вакансии без явно проставленного
-- приоритета остаются NULL → UI показывает нейтральный «не задан».
-- ════════════════════════════════════════════════════════════════════════

ALTER TABLE public.vacancies
  ADD COLUMN IF NOT EXISTS priority TEXT
    CHECK (priority IS NULL OR priority IN ('высокий', 'средний', 'низкий'));
