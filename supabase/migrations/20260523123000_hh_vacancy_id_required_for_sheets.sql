-- Контракт (2026-05-23):
--   • Раньше: в /api/sync/sheets вакансия искалась по hh_vacancy_id, иначе fallback
--     на fuzzy-match названия через RPC find_vacancy_by_title (порог 0.8). Это давало
--     ложные срабатывания и сложно дебажилось.
--   • Теперь: импорт ТРЕБУЕТ непустую колонку "HH ID" (только цифры) в листе «Вакансии».
--     Строки без HH ID — пропускаются (skipped_no_hh_id). Поиск — строго по
--     vacancies.hh_vacancy_id (точное совпадение). Fuzzy-RPC из этого флоу убрана.
--   • vacancies.hh_vacancy_id ОСТАЁТСЯ nullable: вакансию по-прежнему можно создать
--     вручную без HH ID, но синхронизация из Sheets такую вакансию не подхватит.
--
-- RPC find_vacancy_by_title и fuzzy_match_vacancy остаются в схеме на случай иных
-- сценариев (например, разовых сверок), но не вызываются из flow sync/sheets.
-- ════════════════════════════════════════════════════════════════════════

